  let lang = 'es';

  function t(key, vars = {}) {
    let value = STRINGS[lang][key] ?? STRINGS.es[key] ?? key;
    if (typeof value === 'object') value = vars.n === 1 ? value.one : value.other;
    return value.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
  }

  /** Mensaje de un error: traduce "KG:CODIGO|detalle"; cualquier otro texto se muestra tal cual. */
  function errorText(message, formatDetail = (code, d) => d) {
    const text = String(message || '').replace(/^Error invoking remote method '[^']+':\s*(Error:\s*)?/, '');
    const m = /KG:(\w+)(?:\|([\s\S]*))?/.exec(text);
    if (!m) return text;
    const template = ERRORS[lang][m[1]] ?? ERRORS.es[m[1]];
    if (!template) return m[2] || m[1];
    return template.replace('{detail}', formatDetail(m[1], m[2] || ''));
  }

  function setLanguage(next) {
    lang = STRINGS[next] ? next : 'es';
    document.documentElement.lang = lang;
  }

  /** Aplica los textos fijos de index.html. */
